CREATE TABLE DETALLE_VENTAS(
IdDetalleVenta INT PRIMARY KEY IDENTITY(1,1),
IdVenta INT,
IdProducto INT,
PrecioUnitario DECIMAL(18,2),
Cantidad INT,
CONSTRAINT  fk_DetalleVentas_Producto FOREIGN KEY(IdProducto) REFERENCES PRODUCTOS(IdProducto),
CONSTRAINT  fk_DetalleVentas_Ventas FOREIGN KEY(IdVenta) REFERENCES VENTAS(IdVenta),
FechaDetalleVenta DATETIME DEFAULT GETDATE()
)

CREATE TABLE COMPRAS(
IdCompras INT PRIMARY KEY IDENTITY(1,1),
IdProducto INT,
Cantidad INT,
Precio DECIMAL(18,2),
Total DECIMAL(18,2),
IdProveedor INT,
CONSTRAINT  fk_Compras_Producto FOREIGN KEY(IdProducto) REFERENCES PRODUCTOS(IdProducto),
FechaCompra DATETIME DEFAULT GETDATE(),
CONSTRAINT  fk_Compras_Proveedor FOREIGN KEY(IdProveedor) REFERENCES PROVEEDOR(IdProveedor),
)

CREATE TABLE DETALLE_COMPRA(
IdDetalleCompra INT PRIMARY KEY IDENTITY(1,1),
IdCompra INT,
IdProducto INT,
PrecioUnitario DECIMAL(18,2),
Cantidad INT,
IdProveedor INT,
CONSTRAINT  fk_DetalleCompra_Producto FOREIGN KEY(IdProducto) REFERENCES PRODUCTOS(IdProducto),
CONSTRAINT  fk_DetalleCompra_Compras FOREIGN KEY(IdCompra) REFERENCES COMPRAS(IdCompras),
CONSTRAINT  fk_DetalleCompra_Proveedor FOREIGN KEY(IdProveedor) REFERENCES PROVEEDOR(IdProveedor),
FechaDetalleCompraa DATETIME DEFAULT GETDATE()
)