CREATE PROCEDURE SP_AGREGAR_CARGO(
@Cargo VARCHAR(50)
)AS BEGIN
INSERT INTO CARGO(Cargo)
VALUES(@Cargo)
END

CREATE PROCEDURE SP_ACTUALIZAR_CARGO(
@IdCargo INT, 
@Cargo VARCHAR(50)
)AS BEGIN
UPDATE CARGO SET Cargo = @Cargo WHERE IdCargo = @IdCargo
END

CREATE PROCEDURE SP_ELIMINAR_CARGO
@IdCargo INT
AS BEGIN
DELETE FROM CARGO WHERE IdCargo = @IdCargo
END